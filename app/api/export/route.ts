import { NextRequest, NextResponse } from 'next/server'
import { ERC20_ABI } from '@/lib/constants'
import type { Token } from '@/lib/types'

export async function POST(request: NextRequest) {
  try {
    const { token, format } = await request.json()

    if (!token) {
      return NextResponse.json({ error: 'Token data required' }, { status: 400 })
    }

    const tokenData = token as Token

    switch (format) {
      case 'metadata': {
        const metadata = {
          name: tokenData.name,
          symbol: tokenData.symbol,
          description: tokenData.description,
          image: tokenData.logo,
          decimals: tokenData.decimals,
          totalSupply: tokenData.totalSupply,
          contractAddress: tokenData.contractAddress,
          network: tokenData.network,
          deployedAt: tokenData.deployedAt,
        }
        return new NextResponse(JSON.stringify(metadata, null, 2), {
          headers: {
            'Content-Type': 'application/json',
            'Content-Disposition': `attachment; filename="${tokenData.symbol}-metadata.json"`,
          },
        })
      }

      case 'abi': {
        return new NextResponse(JSON.stringify(ERC20_ABI, null, 2), {
          headers: {
            'Content-Type': 'application/json',
            'Content-Disposition': `attachment; filename="${tokenData.symbol}-abi.json"`,
          },
        })
      }

      case 'solidity': {
        const solidity = generateSolidityContract(tokenData)
        return new NextResponse(solidity, {
          headers: {
            'Content-Type': 'text/plain',
            'Content-Disposition': `attachment; filename="${tokenData.symbol}.sol"`,
          },
        })
      }

      case 'all': {
        const metadata = {
          name: tokenData.name,
          symbol: tokenData.symbol,
          description: tokenData.description,
          image: tokenData.logo,
          decimals: tokenData.decimals,
          totalSupply: tokenData.totalSupply,
          contractAddress: tokenData.contractAddress,
          network: tokenData.network,
          deployedAt: tokenData.deployedAt,
        }

        const solidity = generateSolidityContract(tokenData)

        const zipContent = JSON.stringify({
          metadata,
          abi: ERC20_ABI,
          solidity,
        }, null, 2)

        return new NextResponse(zipContent, {
          headers: {
            'Content-Type': 'application/json',
            'Content-Disposition': `attachment; filename="${tokenData.symbol}-export.json"`,
          },
        })
      }

      default:
        return NextResponse.json({ error: 'Invalid format' }, { status: 400 })
    }
  } catch (error) {
    console.error('Export error:', error)
    return NextResponse.json({ error: 'Export failed' }, { status: 500 })
  }
}

function generateSolidityContract(token: Token): string {
  const constructorArgs = `string memory name_ = "${token.name.replace(/"/g, '\\"')}";\n        string memory symbol_ = "${token.symbol.replace(/"/g, '\\"')}";\n        uint256 initialSupply = ${token.totalSupply};`

  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

/**
 * @title ${token.name} (${token.symbol})
 * @dev ERC-20 Token generated by TokenForge
 * @notice ${token.description || 'No description provided'}
 */

import "@openzeppelin/contracts/token/ERC20/ERC20.sol";
import "@openzeppelin/contracts/access/Ownable.sol";

contract ${token.symbol} is ERC20, Ownable {
    constructor() ERC20("", "") Ownable(msg.sender) {
        _mint(msg.sender, ${token.totalSupply});
    }

    function mint(address to, uint256 amount) external onlyOwner {
        _mint(to, amount);
    }

    function burn(uint256 amount) external {
        _burn(msg.sender, amount);
    }
}
`
}